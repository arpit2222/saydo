import { Router, Request, Response } from 'express';
import { Server } from '@modelcontextprotocol/sdk/server/index.js';
import { StreamableHTTPServerTransport } from '@modelcontextprotocol/sdk/server/streamableHttp.js';
import {
  ListToolsRequestSchema,
  CallToolRequestSchema,
  ErrorCode,
  McpError,
} from '@modelcontextprotocol/sdk/types.js';
import { getAppByPublicKey, getSkills, getPolicies, saveRun, saveRunStep, updateRunStatus, mockDb } from '../lib/supabase.js';
import { evaluate } from '@saydo/shared';
import { logger } from '../lib/logger.js';

export const mcpRouter: Router = Router();

// Helper to authenticate request and resolve target app
async function resolveApp(req: Request) {
  const apiKeyHeader =
    req.headers['x-api-key'] ||
    req.headers['x-saydo-key'] ||
    req.headers['x-app-key'] ||
    req.query.apiKey ||
    req.query.app_key;

  let apiKey = typeof apiKeyHeader === 'string' ? apiKeyHeader : 'pk_demo_dehix';

  if (!apiKey && req.headers.authorization?.startsWith('Bearer ')) {
    apiKey = req.headers.authorization.slice(7).trim();
  }

  let app = await getAppByPublicKey(apiKey);
  if (!app) {
    app = Array.from(mockDb.apps.values())[0] || null;
  }
  return app;
}

// Convert SkillDefinition to MCP Tool JSON Schema
function skillToMcpTool(skill: any) {
  const properties: Record<string, any> = {};
  const required: string[] = [];

  // Map inputs from skill
  if (skill.inputs) {
    for (const [key, def] of Object.entries<any>(skill.inputs)) {
      properties[key] = {
        type: def.type === 'number' ? 'number' : def.type === 'boolean' ? 'boolean' : 'string',
        description: def.description || `Parameter ${key}`,
      };
      if (Array.isArray(def.enum)) {
        properties[key].enum = def.enum;
      }
      if (def.required) {
        required.push(key);
      }
    }
  }

  // Write operations require confirm: true
  if (skill.is_write) {
    properties['confirm'] = {
      type: 'boolean',
      description: 'Explicit user confirmation required for write operations. Must be true to execute.',
    };
  }

  return {
    name: skill.name,
    description: skill.description || skill.title || `Execute ${skill.name}`,
    inputSchema: {
      type: 'object' as const,
      properties,
      required: required.length > 0 ? required : undefined,
    },
  };
}

// Build and configure McpServer for an app
function createSayDoMcpServer(app: any) {
  const server = new Server(
    {
      name: `saydo-${app.name.toLowerCase().replace(/[^a-z0-9]/g, '-')}`,
      version: '0.1.0',
    },
    {
      capabilities: {
        tools: {},
      },
      instructions: `This server provides typed tools generated by SayDo for ${app.name}. Write tools require confirm: true in arguments. Dual-layer platform policies are enforced on all actions.`,
    }
  );

  // 1. tools/list handler
  server.setRequestHandler(ListToolsRequestSchema, async () => {
    const allSkills = await getSkills(app.id);
    const activeSkills = allSkills.filter((s: any) => s.status !== 'disabled');
    const tools = activeSkills.map(skillToMcpTool);

    return {
      tools,
    };
  });

  // 2. tools/call handler
  server.setRequestHandler(CallToolRequestSchema, async (request) => {
    const { name, arguments: rawArgs } = request.params;
    const args = (rawArgs || {}) as Record<string, any>;
    const startTime = Date.now();

    const allSkills = await getSkills(app.id);
    const skill = allSkills.find((s: any) => s.name === name);

    if (!skill || skill.status === 'disabled') {
      throw new McpError(ErrorCode.MethodNotFound, `Tool not found or disabled: ${name}`);
    }

    // 1. Write Confirmation Check
    if (skill.is_write && args.confirm !== true) {
      return {
        content: [
          {
            type: 'text',
            text: `Action "${skill.name}" is a write operation and requires explicit confirmation. Please review the parameters and call this tool again with confirm: true.\n\nParameters:\n${JSON.stringify(args, null, 2)}`,
          },
        ],
        isError: false,
      };
    }

    // 2. Policy Guardrails Enforcement
    const policies = await getPolicies(app.id);
    const check = evaluate(skill, args, { userRole: 'mcp-agent', env: {} }, policies);

    if (!check.allowed) {
      const violationMsg = check.violations[0]?.message || 'Blocked by security policy';
      // Record blocked run in telemetry
      const run = await saveRun({
        app_id: app.id,
        user_message: `MCP Tool Call: ${name}`,
        status: 'blocked',
        model_agent: 'mcp-client',
        channel: 'mcp',
        total_ms: Date.now() - startTime,
      });
      await saveRunStep({
        run_id: run.id,
        idx: 1,
        skill_name: name,
        args,
        policy_result: check,
        confirmed: Boolean(args.confirm),
        http_status: 403,
        response: { error: violationMsg },
        verified: false,
        latency_ms: Date.now() - startTime,
      });

      return {
        content: [
          {
            type: 'text',
            text: `Action blocked by platform policy: ${violationMsg}`,
          },
        ],
        isError: true,
      };
    }

    // 3. Server-side Execution against Host Application with X-Agent-Token
    const hostBaseUrl = process.env.HOST_URL || app.allowed_origins?.[0] || 'http://localhost:3000';
    let url = `${hostBaseUrl}${skill.path}`;

    const headers: Record<string, string> = {
      'Content-Type': 'application/json',
      'X-Agent-Token': process.env.AGENT_TOKEN || 'saydo_mcp_agent_token_secret',
    };

    let fetchOptions: RequestInit = {
      method: skill.method,
      headers,
    };

    if (skill.method === 'GET') {
      const qParams = new URLSearchParams();
      for (const [k, v] of Object.entries(args)) {
        if (k !== 'confirm' && v !== undefined && v !== null) {
          qParams.append(k, String(v));
        }
      }
      const qStr = qParams.toString();
      if (qStr) url += (url.includes('?') ? '&' : '?') + qStr;
    } else {
      // Clean args (strip confirm parameter from host API payload)
      const { confirm, ...payload } = args;
      fetchOptions.body = JSON.stringify(payload);
    }

    try {
      const apiRes = await fetch(url, fetchOptions);
      const resJson = await apiRes.json().catch(() => ({ status: apiRes.status, statusText: apiRes.statusText }));
      const latencyMs = Date.now() - startTime;

      // 4. Log run with channel = 'mcp'
      const run = await saveRun({
        app_id: app.id,
        user_message: `MCP Tool Call: ${name}`,
        status: apiRes.ok ? 'completed' : 'failed',
        model_agent: 'mcp-client',
        channel: 'mcp',
        total_ms: latencyMs,
      });

      await saveRunStep({
        run_id: run.id,
        idx: 1,
        skill_name: name,
        args,
        policy_result: check,
        confirmed: Boolean(args.confirm),
        http_status: apiRes.status,
        response: resJson,
        verified: apiRes.ok,
        latency_ms: latencyMs,
      });

      return {
        content: [
          {
            type: 'text',
            text: JSON.stringify(resJson, null, 2),
          },
        ],
        isError: !apiRes.ok,
      };
    } catch (err: any) {
      logger.error({ err: err.message, tool: name }, 'Server-side MCP execution failed');
      return {
        content: [
          {
            type: 'text',
            text: `Execution failed: ${err.message}`,
          },
        ],
        isError: true,
      };
    }
  });

  return server;
}

// Mount Streamable HTTP MCP Endpoint at /mcp
mcpRouter.all('/', async (req: Request, res: Response) => {
  const app = await resolveApp(req);
  if (!app) {
    return res.status(404).json({ error: 'App not found for MCP' });
  }

  // Handle standard JSON-RPC 2.0 direct HTTP POST for maximum compatibility
  if (req.method === 'POST' && req.body && req.body.jsonrpc === '2.0') {
    const { id, method, params } = req.body;

    if (method === 'initialize') {
      return res.json({
        jsonrpc: '2.0',
        id,
        result: {
          protocolVersion: '2024-11-05',
          capabilities: { tools: {} },
          serverInfo: {
            name: `saydo-${app.name.toLowerCase().replace(/[^a-z0-9]/g, '-')}`,
            version: '0.1.0',
          },
        },
      });
    }

    if (method === 'tools/list') {
      const allSkills = await getSkills(app.id);
      const activeSkills = allSkills.filter((s: any) => s.status !== 'disabled');
      const tools = activeSkills.map(skillToMcpTool);
      return res.json({
        jsonrpc: '2.0',
        id,
        result: { tools },
      });
    }

    if (method === 'tools/call') {
      const mcpServer = createSayDoMcpServer(app);
      try {
        const result = await (mcpServer as any)._registeredTools?.get(params.name)?.handler?.(params.arguments) ||
          await (async () => {
            // Direct tool runner fallback
            const { name, arguments: rawArgs } = params;
            const args = (rawArgs || {}) as Record<string, any>;
            const startTime = Date.now();
            const allSkills = await getSkills(app.id);
            const skill = allSkills.find((s: any) => s.name === name);

            if (!skill || skill.status === 'disabled') {
              return {
                content: [{ type: 'text', text: `Tool not found or disabled: ${name}` }],
                isError: true,
              };
            }

            // Write confirm check
            if (skill.is_write && args.confirm !== true) {
              return {
                content: [
                  {
                    type: 'text',
                    text: `Action "${skill.name}" is a write operation and requires explicit confirmation. Please call this tool again with confirm: true.`,
                  },
                ],
                isError: false,
              };
            }

            // Policy check
            const policies = await getPolicies(app.id);
            const check = evaluate(skill, args, { userRole: 'mcp-agent', env: {} }, policies);
            if (!check.allowed) {
              return {
                content: [{ type: 'text', text: `Action blocked by platform policy: ${check.violations[0]?.message || 'Blocked'}` }],
                isError: true,
              };
            }

            // Execute
            const hostBaseUrl = process.env.HOST_URL || app.allowed_origins?.[0] || 'http://localhost:3000';
            let url = `${hostBaseUrl}${skill.path}`;
            const headers: Record<string, string> = {
              'Content-Type': 'application/json',
              'X-Agent-Token': process.env.AGENT_TOKEN || 'saydo_mcp_agent_token_secret',
            };

            let fetchOptions: RequestInit = { method: skill.method, headers };
            if (skill.method === 'GET') {
              const qParams = new URLSearchParams();
              for (const [k, v] of Object.entries(args)) {
                if (k !== 'confirm' && v !== undefined && v !== null) qParams.append(k, String(v));
              }
              const qStr = qParams.toString();
              if (qStr) url += (url.includes('?') ? '&' : '?') + qStr;
            } else {
              const { confirm, ...payload } = args;
              fetchOptions.body = JSON.stringify(payload);
            }

            const apiRes = await fetch(url, fetchOptions);
            const resJson = await apiRes.json().catch(() => ({ status: apiRes.status }));
            const latencyMs = Date.now() - startTime;

            // Telemetry log with channel = 'mcp'
            const run = await saveRun({
              app_id: app.id,
              user_message: `MCP Tool Call: ${name}`,
              status: apiRes.ok ? 'completed' : 'failed',
              model_agent: 'mcp-client',
              channel: 'mcp',
              total_ms: latencyMs,
            });
            await saveRunStep({
              run_id: run.id,
              idx: 1,
              skill_name: name,
              args,
              policy_result: check,
              confirmed: Boolean(args.confirm),
              http_status: apiRes.status,
              response: resJson,
              verified: apiRes.ok,
              latency_ms: latencyMs,
            });

            return {
              content: [{ type: 'text', text: JSON.stringify(resJson, null, 2) }],
              isError: !apiRes.ok,
            };
          })();

        return res.json({
          jsonrpc: '2.0',
          id,
          result,
        });
      } catch (err: any) {
        return res.json({
          jsonrpc: '2.0',
          id,
          error: { code: -32603, message: err.message },
        });
      }
    }

    if (method === 'ping') {
      return res.json({ jsonrpc: '2.0', id, result: {} });
    }
  }

  // Handle through official MCP StreamableHTTPServerTransport
  try {
    const mcpServer = createSayDoMcpServer(app);
    const transport = new StreamableHTTPServerTransport({
      sessionIdGenerator: undefined, // stateless HTTP mode
    });

    await mcpServer.connect(transport);
    await transport.handleRequest(req, res, req.body);
  } catch (err: any) {
    logger.error({ err: err.message }, 'MCP transport error');
    if (!res.headersSent) {
      res.status(500).json({ error: err.message });
    }
  }
});
